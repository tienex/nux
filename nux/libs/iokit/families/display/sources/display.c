/**
 * @brief VESA BIOS Extensions (VBE) structures
 */
#define VBE_SIGNATURE               0x4F

typedef struct _VBE_INFO_BLOCK {
    CHAR8   Signature[4];           /**< "VESA" signature */
    UINT16  Version;                /**< VBE version (0x0300 = 3.0) */
    UINT32  OEMStringPtr;           /**< OEM string pointer */
    UINT32  Capabilities;           /**< Capabilities */
    UINT32  VideoModePtr;           /**< Video mode list pointer */
    UINT16  TotalMemory;            /**< Total memory (64KB blocks) */
    UINT16  OEMSoftwareRev;         /**< OEM software revision */
    UINT32  OEMVendorNamePtr;       /**< OEM vendor name pointer */
    UINT32  OEMProductNamePtr;      /**< OEM product name pointer */
    UINT32  OEMProductRevPtr;       /**< OEM product revision pointer */
    UINT8   Reserved[222];          /**< Reserved */
    UINT8   OEMData[256];           /**< OEM data */
} VBE_INFO_BLOCK;

typedef struct _VBE_MODE_INFO {
    UINT16  ModeAttributes;         /**< Mode attributes */
    UINT8   WinAAttributes;         /**< Window A attributes */
    UINT8   WinBAttributes;         /**< Window B attributes */
    UINT16  WinGranularity;         /**< Window granularity */
    UINT16  WinSize;                /**< Window size */
    UINT16  WinASegment;            /**< Window A segment */
    UINT16  WinBSegment;            /**< Window B segment */
    UINT32  WinFuncPtr;             /**< Window function pointer */
    UINT16  BytesPerScanLine;       /**< Bytes per scan line */
    UINT16  XResolution;            /**< X resolution */
    UINT16  YResolution;            /**< Y resolution */
    UINT8   XCharSize;              /**< Character width */
    UINT8   YCharSize;              /**< Character height */
    UINT8   NumberOfPlanes;         /**< Number of planes */
    UINT8   BitsPerPixel;           /**< Bits per pixel */
    UINT8   NumberOfBanks;          /**< Number of banks */
    UINT8   MemoryModel;            /**< Memory model */
    UINT8   BankSize;               /**< Bank size */
    UINT8   NumberOfImagePages;     /**< Number of image pages */
    UINT8   Reserved1;              /**< Reserved */
    UINT8   RedMaskSize;            /**< Red mask size */
    UINT8   RedFieldPosition;       /**< Red field position */
    UINT8   GreenMaskSize;          /**< Green mask size */
    UINT8   GreenFieldPosition;     /**< Green field position */
    UINT8   BlueMaskSize;           /**< Blue mask size */
    UINT8   BlueFieldPosition;      /**< Blue field position */
    UINT8   RsvdMaskSize;           /**< Reserved mask size */
    UINT8   RsvdFieldPosition;      /**< Reserved field position */
    UINT8   DirectColorModeInfo;    /**< Direct color mode info */
    UINT32  PhysBasePtr;            /**< Physical framebuffer address */
    UINT32  Reserved2;              /**< Reserved */
    UINT16  Reserved3;              /**< Reserved */
    UINT8   Reserved4[206];         /**< Reserved */
} VBE_MODE_INFO;

/**
 * @brief Display controller implementation
 */
typedef struct _DISPLAY_CONTROLLER_IMPL {
    IIODisplayController        Vtbl;               /**< Virtual function table */
    IIOService                 *pService;           /**< Underlying service */
    DISPLAY_CONTROLLER_INFO     Info;               /**< Controller information */
    DISPLAY_MODE                CurrentMode;        /**< Current display mode */
    FRAMEBUFFER_INFO            FramebufferInfo;    /**< Framebuffer information */
    VOID                       *pFramebufferVirt;   /**< Mapped framebuffer */
    BOOLEAN                     bInitialized;       /**< Initialization flag */
    UINT32                      uRefCount;          /**< Reference count */
} DISPLAY_CONTROLLER_IMPL;

/**
 * @brief Framebuffer implementation
 */
typedef struct _FRAMEBUFFER_IMPL {
    IIOFramebuffer              Vtbl;               /**< Virtual function table */
    FRAMEBUFFER_INFO            Info;               /**< Framebuffer information */
    VOID                       *pMappedAddress;     /**< Mapped virtual address */
    BOOLEAN                     bMapped;            /**< Mapping flag */
    UINT32                      uRefCount;          /**< Reference count */
} FRAMEBUFFER_IMPL;

