static IO_RETURN
Framebuffer_SetPixel(
    IIOFramebuffer *pThis,
    UINT32 uX,
    UINT32 uY,
    UINT32 uColor
    )
{
    FRAMEBUFFER_IMPL *pImpl = (FRAMEBUFFER_IMPL *)pThis;
    UINT32 uOffset;
    volatile UINT32 *pPixel;

    if (pImpl == NULL || !pImpl->bMapped) {
        return IO_BAD_ARGUMENT;
    }

    if (uX >= pImpl->Info.Width || uY >= pImpl->Info.Height) {
        return IO_BAD_ARGUMENT;
    }

    uOffset = uY * pImpl->Info.Pitch + (uX * (pImpl->Info.BitsPerPixel / 8));
    pPixel = (volatile UINT32 *)((UINT8 *)pImpl->pMappedAddress + uOffset);
    *pPixel = uColor;

    return IO_SUCCESS;
}

